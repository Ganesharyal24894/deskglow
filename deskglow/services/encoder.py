"""Rendering light commands into the bytes a controller understands."""
from typing import Protocol


class FrameEncoder(Protocol):
    def power(self, on: bool) -> bytes: ...

    def color(self, r: float, g: float, b: float) -> bytes: ...

    def brightness(self, pct: float) -> bytes: ...

    def effect(self, effect_id: int) -> bytes: ...

    def speed(self, pct: float) -> bytes: ...

    def status_query(self) -> bytes: ...
